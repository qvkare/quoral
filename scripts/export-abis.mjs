// Exports ABIs from Foundry artifacts into packages/shared (typed TS) and packages/indexer/abis (JSON),
// and copies deployments/*.json into packages/shared/src/deployments.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "contracts/out");
const contracts = [
  "InventoryVault", "Heartbeat", "Paystream", "BondVault", "DisclosureRegistry",
  "RFQAuction", "AgreementFactory", "CREKeeperReceiver",
];
const extra = { IKuruOrderBook: "IKuru.sol", MockOrderBook: "MockKuru.sol", MockERC20: "MockKuru.sol" };

// RFQAuction → rfqAuction, CREKeeperReceiver → creKeeperReceiver, IKuruOrderBook → iKuruOrderBook
const lc = (n) => n.replace(/^[A-Z]+(?=[A-Z][a-z]|$)|^[A-Z]/, (m) => m.toLowerCase());
let ts = "// AUTO-GENERATED by scripts/export-abis.mjs. Do not edit.\n\n";
mkdirSync(join(root, "packages/indexer/abis"), { recursive: true });
for (const [name, file] of [...contracts.map((c) => [c, `${c}.sol`]), ...Object.entries(extra)]) {
  const art = JSON.parse(readFileSync(join(out, file, `${name}.json`), "utf8"));
  ts += `export const ${lc(name)}Abi = ${JSON.stringify(art.abi, null, 2)} as const;\n\n`;
  writeFileSync(join(root, "packages/indexer/abis", `${name}.json`), JSON.stringify(art.abi, null, 2));
}
writeFileSync(join(root, "packages/shared/src/abis.ts"), ts);

const depDir = join(root, "contracts/deployments");
const deps = {};
if (existsSync(depDir)) {
  for (const f of readdirSync(depDir).filter((f) => f.endsWith(".json"))) {
    deps[f.replace(".json", "")] = JSON.parse(readFileSync(join(depDir, f), "utf8"));
  }
}
writeFileSync(
  join(root, "packages/shared/src/deployments.json"),
  JSON.stringify(deps, null, 2) + "\n",
);
console.log(`exported ${contracts.length + Object.keys(extra).length} ABIs, ${Object.keys(deps).length} deployment(s)`);
